export type EmblemName = keyof typeof EMBLEMS;

/** 문양이 지정되지 않은 원천에 쓰는 도메인 기본값. */
export const DOMAIN_EMBLEM: Record<string, string> = {
  'greco-roman-myth': 'maze',
  'bible-ot': 'seed',
  'bible-nt': 'hand',
  history: 'column',
  literature: 'mask',
};

export const emblemFor = (emblem: string | undefined, domain: string): string =>
  (emblem && emblem in EMBLEMS ? emblem : undefined) ?? DOMAIN_EMBLEM[domain] ?? 'maze';

export default function Emblem({
  name,
  size = 96,
  strokeWidth = 4,
  className,
  style,
}: {
  name: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: React.CSSProperties;
}) {
  const shape = EMBLEMS[name] ?? EMBLEMS.maze!;
  return (
    <svg
      viewBox="0 0 100 100"
      width={size}
      height={size}
      className={className}
      style={style}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {shape.d?.map((d, i) => (
        <path key={`d${i}`} d={d} />
      ))}
      {shape.dashed?.map((d, i) => (
        <path key={`s${i}`} d={d} strokeDasharray="7 7" />
      ))}
      {shape.circles?.map(([cx, cy, r, filled], i) => (
        <circle key={`c${i}`} cx={cx} cy={cy} r={r} fill={filled ? 'currentColor' : 'none'} />
      ))}
    </svg>
  );
}
